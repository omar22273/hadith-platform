from __future__ import annotations


def ih(index: int, prefix: str):
    return ("ih", index, prefix)


def isd(first: str, last: str | None = None, occ: int | None = None):
    """`occ`: ترتيب ورود `first` من الصفر حين ترد في أكثر من موضع (كتراجم متكررة لخبر واحد)."""
    return ("is", first, last, occ)


def bk(number: int):
    return ("bk", number)


def basis(source: str, phrase: str):
    """شاهد حرفي لشريط البوصلة: المصدر وعبارة منه (بلا تشكيل للبخاري)."""
    return (source, phrase)


